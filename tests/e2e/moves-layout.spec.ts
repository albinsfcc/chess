import { expect, test } from "@playwright/test";
import { build } from "esbuild";
import { Chess } from "chess.js";

test("move table keeps the breakdown in the modal and local branches at their anchors", async ({ page }, testInfo) => {
  test.setTimeout(60000);
  const worker = (await build({ entryPoints: ["tests/fixtures/game-analysis-worker.ts"], bundle: true, write: false, format: "iife", platform: "browser" })).outputFiles[0].text;
  await page.route("**/engines/analysis-worker.js", route => route.fulfill({ contentType: "application/javascript", body: worker }));
  await page.goto("/");
  if (await page.getByRole("button", { name: "Import", exact: true }).isVisible()) await page.getByRole("button", { name: "Import", exact: true }).click();
  await page.getByRole("button", { name: "Paste PGN", exact: true }).click();
  await page.getByLabel("PGN games", { exact: true }).fill('[White "Explorer"]\n[Black "Opponent"]\n1. e4 e5 2. Nf3 Nc6 3. Bc4 Bc5 1-0');
  await page.getByRole("button", { name: "Import 1 game", exact: true }).click();
  await expect(page.getByRole("dialog").getByRole("heading", { name: "Move strength breakdown", exact: true })).toBeVisible({ timeout: 25000 });
  await page.getByRole("button", { name: "Start review", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Move strength breakdown", exact: true })).toHaveCount(0);
  const moves = page.getByRole("region", { name: "Moves & variations", exact: true });
  const performance = page.getByRole("region", { name: "Player performance", exact: true });
  const trend = page.getByRole("region", { name: "Evaluation trend", exact: true });
  expect(await performance.evaluate(element => !!(element.compareDocumentPosition(document.querySelector('[aria-labelledby="moves-heading"]')!) & Node.DOCUMENT_POSITION_FOLLOWING))).toBe(true);
  expect(await moves.evaluate(element => !!(element.compareDocumentPosition(document.querySelector('[aria-label="Evaluation trend"]')!) & Node.DOCUMENT_POSITION_FOLLOWING))).toBe(true);
  expect(await trend.evaluate(element => !!(element.compareDocumentPosition(document.querySelector('[aria-label="Game headers"]')!) & Node.DOCUMENT_POSITION_FOLLOWING))).toBe(true);
  expect((await performance.boundingBox())!.height).toBeLessThan(200);
  await expect(page.getByRole("button", { name: "Review game", exact: true })).toHaveCount(0);
  await expect(page.getByTestId("board-navigation").getByRole("button", { name: "Focus mode", exact: true })).toBeVisible();
  expect(await page.getByTestId("board-navigation").evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
  await page.screenshot({ path: `artifacts/review-order-${testInfo.project.name}.png`, fullPage: true });
  await page.getByRole("button", { name: "Focus mode", exact: true }).click();
  await expect(page.getByLabel("Current opening", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Review game", exact: true })).toHaveCount(0);
  await expect(performance).toBeVisible();
  expect(await page.getByTestId("board-navigation").evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
  await page.screenshot({ path: `artifacts/review-focus-${testInfo.project.name}.png`, fullPage: true });
  await page.getByRole("button", { name: "Exit focus", exact: true }).click();
  await moves.getByRole("button", { name: "Main line 1. e4", exact: true }).click();
  await page.getByTestId("square-d7").click(); await page.getByTestId("square-d5").click();
  const local = moves.locator("details").filter({ has: page.locator("summary", { hasText: "Local variation 1 from ply 1" }) });
  await expect(local).toHaveAttribute("open", "");
  await expect(local.getByRole("button", { name: "Variation 1... d5", exact: true })).toHaveAttribute("aria-current", "step");
  expect(await local.evaluate(element => element.previousElementSibling?.textContent)).toContain("e4");
  expect(await local.evaluate(element => element.nextElementSibling?.textContent)).toContain("e5");
  await page.getByRole("button", { name: "Previous move", exact: true }).click();
  await page.getByRole("button", { name: "Next move", exact: true }).click();
  await expect(moves.getByRole("button", { name: "Main line 1... e5", exact: true })).toHaveAttribute("aria-current", "step");
  await local.locator("summary").click();
  await local.getByRole("button", { name: "Variation 1... d5", exact: true }).click();
  await page.getByTestId("square-e4").click(); await page.getByTestId("square-d5").click();
  await local.getByRole("button", { name: "Variation 1... d5", exact: true }).click();
  await page.getByTestId("square-b1").click(); await page.getByTestId("square-c3").click();
  await expect(local.getByText("Local variation 2 from ply 2", { exact: true })).toBeVisible();
  await expect(local.getByRole("button", { name: "Variation 2. Nc3", exact: true })).toHaveAttribute("aria-current", "step");
  await moves.scrollIntoViewIfNeeded();
  await moves.screenshot({ path: `artifacts/moves-layout-${testInfo.project.name}.png` });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await moves.getByRole("button", { name: "Main line 2. Nf3", exact: true }).click();
  await page.getByRole("button", { name: "Next move", exact: true }).click();
  await expect(moves.getByRole("button", { name: "Main line 2... Nc6", exact: true })).toHaveAttribute("aria-current", "step");
  await moves.getByRole("button", { name: "Main line 3. Bc4", exact: true }).click();
  await page.getByRole("tab", { name: "Opening", exact: true }).click();
  const related = page.getByRole("region", { name: "Related opening variations", exact: true });
  await related.getByRole("button", { name: /^Explore / }).first().click();
  const dialog = page.getByRole("dialog");
  await expect(page.getByTestId("opening-board")).toBeVisible();
  const original = await page.getByTestId("opening-board").getAttribute("data-fen");
  await dialog.getByRole("button", { name: "Previous opening move", exact: true }).click();
  await expect(page.getByTestId("opening-board")).not.toHaveAttribute("data-fen", original!);
  await dialog.getByRole("button", { name: "Reset opening", exact: true }).click();
  await expect(page.getByTestId("opening-board")).toHaveAttribute("data-fen", original!);
  const legal = new Chess(original!).moves({ verbose: true })[0];
  await page.getByTestId(`opening-square-${legal.from}`).click();
  await page.getByTestId(`opening-square-${legal.to}`).click();
  const expected = new Chess(original!); expected.move(legal);
  await expect(page.getByTestId("opening-board")).toHaveAttribute("data-fen", expected.fen());
  await dialog.getByRole("button", { name: "Reset opening", exact: true }).click();
  await dialog.screenshot({ path: `artifacts/opening-explorer-${testInfo.project.name}.png` });
  await dialog.getByRole("button", { name: "Close", exact: true }).click();
  await page.getByRole("tab", { name: "Moves", exact: true }).click();
  await expect(moves.getByRole("button", { name: "Main line 3. Bc4", exact: true })).toHaveAttribute("aria-current", "step");
  await page.getByRole("button", { name: "View full review", exact: true }).click();
  await expect(page.getByRole("dialog").getByRole("heading", { name: "Move strength breakdown", exact: true })).toBeVisible();
});
